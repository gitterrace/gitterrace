//! `tokens.css`: the generated block between its markers, built from the schwarzwald snapshot
//! in `vendor/schwarzwald/kit/tokens`. Colors, fonts, the type scale, the space grid, radius and
//! motion come from there and nowhere else. Fails when a role pair is under its contrast minimum.

#![expect(
    clippy::suboptimal_flops,
    reason = "the arithmetic must round exactly as the reference did, so no fused multiply-add"
)]

use anyhow::{Context as _, Result, bail, ensure};
use serde_json::Value;

use crate::out::Out;

const CSS: &str = "crates/gitterrace-web/static/tokens.css";
const BEGIN: &str = "/* BEGIN generated by xtask/src/theme.rs */";
const END: &str = "/* END generated by xtask/src/theme.rs */";
const THEME: &str = "kandel";
const SCRIM: &str = "#0000004d";
/// Steps of the schwarzwald space grid that `app.css` uses; the rest stays out of the stylesheet.
const SPACE_USED: [usize; 8] = [1, 2, 3, 4, 5, 6, 8, 16];
const SHADOW: (&str, &str) = ("0 8px 28px rgba(16,20,28,.12)", "0 8px 28px rgba(0,0,0,.5)");
const SYNTAX: [&str; 7] = ["comment", "keyword", "string", "constant", "entity", "tag", "param"];

/// Every color of one mode as (role, value), in the stylesheet's order.
type Colours = Vec<(String, String)>;

/// A text, border or fill pair: (foreground, background, minimum contrast).
type Pair = (String, String, f64);

fn hexv(t: &Value, name: &str) -> Result<String> {
    let hex = t.get(name).and_then(|v| v.get("hex")).and_then(Value::as_str);
    Ok(hex.with_context(|| format!("token {name} has no hex"))?.to_lowercase())
}

fn channels(c: &str) -> Result<[u8; 3]> {
    let byte = |i: usize| u8::from_str_radix(c.get(i..i + 2).unwrap_or(""), 16);
    Ok([byte(1)?, byte(3)?, byte(5)?])
}

fn mix(fg: &str, bg: &str, share: f64) -> Result<String> {
    let (a, b) = (channels(fg)?, channels(bg)?);
    let hex: Vec<String> = a
        .iter()
        .zip(b)
        .map(|(x, y)| {
            let v = (f64::from(*x) * share + f64::from(y) * (1.0 - share)).round_ties_even();
            format!("{:02x}", v as u8)
        })
        .collect();
    Ok(format!("#{}", hex.concat()))
}

fn luminance(c: &str) -> Result<f64> {
    let ch = |x: u8| {
        let x = f64::from(x) / 255.0;
        if x <= 0.04045 { x / 12.92 } else { ((x + 0.055) / 1.055).powf(2.4) }
    };
    let [r, g, b] = channels(c)?;
    Ok(0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b))
}

/// WCAG contrast ratio of two #rrggbb colors.
pub(crate) fn contrast(a: &str, b: &str) -> Result<f64> {
    let (la, lb) = (luminance(a)?, luminance(b)?);
    Ok((la.max(lb) + 0.05) / (la.min(lb) + 0.05))
}

/// The role pairs that must keep their contrast. Text needs 4.5:1 on every surface it is drawn
/// on, built from lists so a new token joins the matrix by name. Control borders need 3:1, and
/// the quiet divider `n-4` only has to stay visible, because rules are not a control edge.
fn pairs() -> Vec<Pair> {
    let own = |l: &[&str]| l.iter().map(|s| (*s).to_owned()).collect::<Vec<_>>();
    let page = own(&["n-1", "n-2", "n-3", "header", "raised"]);
    let text = own(&["n-6", "n-7", "n-9", "info", "accent", "add", "del", "warn"]);
    let syntax: Vec<String> = SYNTAX.iter().map(|r| format!("syn-{r}")).collect();
    let rows = own(&["add-bg", "del-bg", "warn-bg", "accent-soft"]);
    let mut out: Vec<Pair> = Vec::new();
    let mut add = |fg: &[String], bg: &[String], need: f64| {
        for f in fg {
            for b in bg {
                out.push((f.clone(), b.clone(), need));
            }
        }
    };
    add(&text, &page, 4.5);
    let syn_bg: Vec<String> =
        own(&["n-1", "n-2", "raised"]).into_iter().chain(rows.clone()).collect();
    add(&syntax, &syn_bg, 4.5);
    add(&own(&["n-9", "n-7", "accent"]), &rows, 4.5);
    add(&own(&["add"]), &own(&["add-hl"]), 4.5);
    add(&own(&["del"]), &own(&["del-hl"]), 4.5);
    add(&own(&["on-accent"]), &own(&["accent"]), 4.5);
    for i in 0..5 {
        add(&[format!("ink-on-heat-{i}")], &[format!("seq-{i}")], 4.5);
    }
    add(&own(&["accent"]), &own(&["n-1", "raised", "header"]), 3.0);
    add(&own(&["n-5"]), &page, 3.0);
    add(&own(&["n-4"]), &own(&["n-1", "n-2", "header", "raised"]), 1.15);
    out
}

fn contrast_problems(light: &Colours, dark: &Colours) -> Result<Vec<String>> {
    let mut bad = Vec::new();
    for (mode, col) in [("light", light), ("dark", dark)] {
        let get = |n: &str| col.iter().find(|(k, _)| k == n).map(|(_, v)| v.as_str());
        for (fg, bg, need) in pairs() {
            let (f, b) = (get(&fg).context(fg.clone())?, get(&bg).context(bg.clone())?);
            let got = contrast(f, b)?;
            if got < need {
                bad.push(format!("{mode}: --{fg} on --{bg} is {got:.2}:1, needs {need}:1"));
            }
        }
    }
    Ok(bad)
}

fn colours(tokens: &Value, mode: &str) -> Result<Colours> {
    let t = &tokens["themes"][THEME][mode];
    let h = |n: &str| hexv(t, n);
    let share = tokens["shares"]["selected-row"].as_f64().context("shares.selected-row")?;
    let ring = if mode == "light" { "66" } else { "80" };
    let accent = h("accent-ink")?;
    let bg = h("surfaces.bg")?;
    // Text on an accent fill: whichever of white and the page ink reads better.
    let on_accent = if contrast(&bg, &accent)? > contrast("#ffffff", &accent)? {
        bg.clone()
    } else {
        "#ffffff".to_owned()
    };
    let mut out: Colours = vec![
        ("n-0".into(), h("surfaces.window")?),
        ("n-1".into(), bg.clone()),
        ("n-2".into(), h("surfaces.soft")?),
        ("n-3".into(), h("surfaces.hover")?),
        ("n-4".into(), h("surfaces.line")?),
        ("n-5".into(), h("surfaces.line-strong")?),
        ("n-6".into(), h("ink.tertiary")?),
        ("n-7".into(), h("ink.secondary")?),
        ("n-9".into(), h("ink.primary")?),
        ("header".into(), h("surfaces.header")?),
        ("raised".into(), h("surfaces.raised")?),
        ("scrim".into(), SCRIM.into()),
        ("accent".into(), accent.clone()),
        ("accent-fg".into(), accent.clone()),
        ("accent-soft".into(), mix(&accent, &bg, share)?),
        ("ring".into(), format!("{accent}{ring}")),
        ("on-accent".into(), on_accent),
        ("add".into(), h("positive")?),
        ("add-bg".into(), h("code.add-row")?),
        ("add-hl".into(), h("code.add-word")?),
        ("del".into(), h("danger")?),
        ("del-bg".into(), h("code.del-row")?),
        ("del-hl".into(), h("code.del-word")?),
        ("warn".into(), h("caution")?),
        ("warn-bg".into(), h("code.warn-row")?),
        ("info".into(), h("info")?),
        ("done".into(), h("positive")?),
    ];
    for i in 0..5 {
        out.push((format!("seq-{i}"), h(&format!("heat.{i}"))?));
    }
    for i in 0..5 {
        out.push((format!("ink-on-heat-{i}"), h(&format!("ink-on-heat.{i}"))?));
    }
    for i in 1..9 {
        out.push((format!("cat-{i}"), h(&format!("series.{i}"))?));
    }
    for r in SYNTAX {
        out.push((format!("syn-{r}"), h(&format!("code.syntax.{r}"))?));
    }
    Ok(out)
}

/// `light-dark()` takes colors only, so a shadow keeps its shape and pairs its color.
fn pair(light: &str, dark: &str) -> String {
    if let (Some((lp, lc)), Some((dp, dc))) = (light.rsplit_once(' '), dark.rsplit_once(' '))
        && lp == dp
    {
        return format!("{lp} light-dark({lc},{dc})");
    }
    format!("light-dark({light},{dark})")
}

/// Every color once, as `light-dark()`; `color-scheme` on `:root` picks the side.
fn palette(light: Colours, dark: Colours) -> String {
    let both = light.into_iter().chain([("shadow-2".to_owned(), SHADOW.0.to_owned())]);
    let other = dark.into_iter().chain([("shadow-2".to_owned(), SHADOW.1.to_owned())]);
    let items: Vec<String> = both
        .zip(other)
        .map(
            |((k, v), (_, o))| {
                if v == o { format!("--{k}:{v};") } else { format!("--{k}:{};", pair(&v, &o)) }
            },
        )
        .collect();
    let rows: Vec<String> = items.chunks(7).map(|c| c.join(" ")).collect();
    format!(":root{{\n{}\n}}", rows.join("\n"))
}

