fn fonts(design: &Value) -> Result<Vec<String>> {
    let f = &design["font"];
    let web = |k: &str| f[k]["web"].as_str().with_context(|| format!("font.{k}.web"));
    ensure!(
        web("title")? == "Fraunces"
            && web("body")?.starts_with("Bricolage")
            && web("mono")? == "JetBrains Mono",
        "the font roles changed in the snapshot"
    );
    let faces = [
        ("Fraunces", "fraunces", "100 900", "optional"),
        ("Bricolage Grotesque", "bricolage-grotesque", "200 800", "optional"),
        ("JetBrains Mono", "jetbrains-mono", "100 800", "optional"),
    ];
    let mut lines: Vec<String> = faces
        .iter()
        .map(|(fam, slug, w, display)| {
            format!(
                "@font-face{{font-family:\"{fam}\";src:url(/static/fonts/{slug}.woff2) \
                 format(\"woff2\");font-weight:{w};font-display:{display}}}"
            )
        })
        .collect();
    // Title and body are `optional` and preloaded by the page head: the browser never swaps
    // them in after first layout, so a late font moves nothing. Mono too: the diff headers
    // and counts use it. A face that missed first paint shows its stand-in: Arial, Georgia,
    // Times or Courier (or their Liberation twins on Linux) sized and spaced like it, so the
    // page still lays out the same.
    lines.extend(BODY_STANDIN.map(str::to_owned));
    lines.extend(TITLE_STANDIN.map(str::to_owned));
    lines.extend(TITLE_STANDIN_TIMES.map(str::to_owned));
    lines.push(MONO_STANDIN.to_owned());
    let stack = |k: &str| -> Result<String> {
        let mut names = vec![web(k)?.to_owned()];
        match k {
            "body" => names.push("Bricolage Standin".to_owned()),
            "title" => {
                names.push("Fraunces Standin".to_owned());
                names.push("Fraunces Standin Times".to_owned());
            }
            _ => names.push("JetBrains Mono Standin".to_owned()),
        }
        for n in f[k]["fallback"].as_array().context("fallback")? {
            names.push(n.as_str().context("fallback name")?.to_owned());
        }
        Ok(names
            .iter()
            .map(|x| if x.contains(' ') { format!("\"{x}\"") } else { x.clone() })
            .collect::<Vec<_>>()
            .join(","))
    };
    lines.push(format!(
        ":root{{--font-title:{};--font-body:{};--font-mono:{},\"SF Mono\",Consolas,monospace;}}",
        stack("title")?,
        stack("body")?,
        stack("mono")?
    ));
    Ok(lines)
}

fn scales(d: &Value) -> Result<String> {
    let names =
        [(11, "2xs"), (12, "xs"), (13, "sm"), (15, "base"), (16, "md"), (20, "lg"), (26, "xl")];
    let mut text: Vec<String> = Vec::new();
    for p in d["type"]["scalePx"].as_array().context("type.scalePx")? {
        let p = p.as_u64().context("type step")?;
        let name = names.iter().find(|(n, _)| *n == p).context("an unnamed type step")?.1;
        text.push(format!("--text-{name}:{p}px;"));
    }
    let mut space: Vec<String> = Vec::new();
    for (i, p) in d["space"]["stepsPx"].as_array().context("space.stepsPx")?.iter().enumerate() {
        if SPACE_USED.contains(&(i + 1)) {
            space.push(format!("--space-{}:{}px;", i + 1, p.as_u64().context("space step")?));
        }
    }
    let m = &d["motion"];
    let easing = m["easing"].as_str().context("motion.easing")?.replace(", ", ",");
    let ms = |k: &str| m["durationMs"][k].as_u64().with_context(|| format!("motion {k}"));
    let motion =
        format!("--ease:{easing};--dur-fast:{}ms;--dur-slow:{}ms;", ms("hover")?, ms("progress")?);
    let px = |v: &Value, what: &str| -> Result<u64> { v.as_u64().with_context(|| what.to_owned()) };
    let size = &d["size"];
    let sizes = format!(
        "--row-h:{}px;--control-h:{}px;--control-h-sm:{}px;--bar-h:{}px;--bar-h-sm:{}px;",
        px(&size["rowPx"], "size.rowPx")?,
        px(&size["controlPx"], "size.controlPx")?,
        px(&size["controlSmPx"], "size.controlSmPx")?,
        px(&size["barPx"], "size.barPx")?,
        px(&size["barSmPx"], "size.barSmPx")?
    );
    let prose = format!(
        "--tracking-label:{};--measure:{};",
        d["type"]["trackingLabel"].as_str().context("type.trackingLabel")?,
        d["type"]["measure"].as_str().context("type.measure")?
    );
    let display = display(&d["type"])?;
    Ok(format!(
        ":root{{{}\n{}\n{sizes}\n{prose}\n{display}\n--radius:{}px;--radius-round:{};\n{motion}}}",
        text.concat(),
        space.concat(),
        d["radius"]["webPx"],
        d["radius"]["round"].as_str().context("radius.round")?
    ))
}

/// The display step, the one landing headline: fluid between its two sizes, both above the top
/// of the scale, as the kit's contract asks.
fn display(ty: &Value) -> Result<String> {
    let dp = &ty["display"];
    let px = |k: &str| dp[k].as_u64().with_context(|| format!("type.display.{k}"));
    let (min, max) = (px("minPx")?, px("maxPx")?);
    let top = ty["scalePx"].as_array().and_then(|s| s.last()).and_then(Value::as_u64);
    let top = top.context("type.scalePx")?;
    ensure!(
        top < min && min < max,
        "type.display needs scale top {top} < minPx {min} < maxPx {max}"
    );
    let fluid = dp["fluid"].as_str().context("type.display.fluid")?;
    let leading = dp["leading"].as_f64().context("type.display.leading")?;
    let tracking = dp["tracking"].as_str().context("type.display.tracking")?;
    let rem = |p: u64| format!("{}rem", p as f64 / 16.0);
    let size = format!("--text-display:clamp({},{fluid},{});", rem(min), rem(max));
    Ok(format!("{size}\n--leading-display:{leading};--tracking-display:{tracking};"))
}

/// The tokens file with its generated block rebuilt.
pub fn render(root: &std::path::Path) -> Result<Out> {
    let snap = root.join("vendor/schwarzwald/kit/tokens");
    let load = |n: &str| -> Result<Value> {
        let text = std::fs::read_to_string(snap.join(n)).with_context(|| format!("reading {n}"))?;
        Ok(serde_json::from_str(&text)?)
    };
    let (tokens, design) = (load("theme-tokens.json")?, load("design-tokens.json")?);
    let (light, dark) = (colours(&tokens, "light")?, colours(&tokens, "dark")?);
    let low = contrast_problems(&light, &dark)?;
    ensure!(low.is_empty(), "contrast under its minimum:\n  {}", low.join("\n  "));
    let mut parts = fonts(&design)?;
    parts.extend([
        scales(&design)?,
        ":root{color-scheme:light}".into(),
        "@media (prefers-color-scheme:dark){:root:not([data-theme=light]){color-scheme:dark}}"
            .into(),
        ":root[data-theme=dark]{color-scheme:dark}".into(),
        palette(light, dark),
    ]);
    let old = std::fs::read_to_string(root.join(CSS)).context("reading tokens.css")?;
    let (Some(b), Some(e)) = (old.find(BEGIN), old.find(END)) else {
        bail!("{CSS} lacks the generated markers");
    };
    let new = format!("{}{BEGIN}\n{}\n{}", &old[..b], parts.join("\n"), &old[e..]);
    Ok(Out::file(CSS, new))
}

