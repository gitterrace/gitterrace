//! The credit for the projects the screenshots show, and the generated overview of the
//! screenshots in `docs/screenshots/README.md`.

use std::fmt::Write as _;

/// The pinned projects the screenshots show, `(name, url, tag)` in order, read from the
/// screenshot corpus pins so the credit links the trees the shots were taken from.
fn pins() -> Vec<(String, String, String)> {
    let mut out: Vec<(String, String, String)> = Vec::new();
    let quoted = |l: &str, key: &str| {
        l.trim().strip_prefix(key).and_then(|t| t.split('\'').next()).map(str::to_owned)
    };
    for line in include_str!("../../scripts/lib/corpus-lib.mjs").lines() {
        if let Some(n) = line.strip_prefix("  ").and_then(|l| l.strip_suffix(": {")) {
            out.push((n.to_owned(), String::new(), String::new()));
        } else if let (Some(u), Some(last)) = (quoted(line, "url: '"), out.last_mut()) {
            last.1 = u;
        } else if let (Some(t), Some(last)) = (quoted(line, "tag: '"), out.last_mut()) {
            last.2 = t;
        }
    }
    out
}

/// The credit for the projects the screenshots show: each name links its pinned release tree,
/// "The screenshots" links the folder they live in. gitterrace's own pin, which the demo
/// shows beside them, is no third party to credit.
pub(crate) fn credit_md() -> String {
    let links: Vec<String> = pins()
        .iter()
        .filter(|(n, _, _)| n != "gitterrace")
        .map(|(n, u, t)| format!("[{n}]({u}/tree/{t})"))
        .collect();
    let names = match links.as_slice() {
        [] => String::new(),
        [one] => one.clone(),
        [rest @ .., last] => format!("{} and {last}", rest.join(", ")),
    };
    format!(
        "[The screenshots](docs/screenshots/) show the open source projects {names}, used \
         under their MIT licenses. They are not affiliated with gitterrace. Thanks to their \
         authors for great tools.\n"
    )
}

/// The corpus repo each shot is taken from, `(shot, repo)`, read from the shot list in
/// `site-shots-run.mjs` so the gallery names what the runner photographs.
fn shot_repos() -> Vec<(String, String)> {
    let mut out = Vec::new();
    let mut name = String::new();
    for line in include_str!("../../scripts/release/site/site-shots-run.mjs").lines() {
        let l = line.trim();
        if let Some(n) = l.strip_prefix("{ name: '").or_else(|| l.strip_prefix("name: '")) {
            n.split('\'').next().unwrap_or_default().clone_into(&mut name);
        }
        if let Some(r) = l.split("path: '/r/").nth(1) {
            let repo = r.split('/').next().unwrap_or_default();
            out.push((name.clone(), repo.to_owned()));
        }
    }
    out
}

/// `docs/screenshots/README.md`: every shot with its description, both color schemes and the
/// pinned tree it shows, then the credit. A forge shows it when the folder is opened.
pub(crate) fn gallery_md() -> String {
    let pins = pins();
    let repos = shot_repos();
    let mut md = String::from(
        "# Screenshots\n\nGenerated by `make docs-gen`, taken by `make site-shots`.\n\n",
    );
    for (stem, alt, caption) in crate::site::SHOTS {
        let _ = write!(md, "## {caption}\n\n{alt}\n\n");
        let _ = write!(
            md,
            "<picture>\n<source media=\"(prefers-color-scheme: dark)\" \
             srcset=\"{stem}-dark.webp\">\n<img src=\"{stem}-light.webp\" alt=\"{alt}\">\n\
             </picture>\n\n"
        );
        let shown = repos
            .iter()
            .find(|(n, _)| n == stem)
            .and_then(|(_, r)| pins.iter().find(|(n, ..)| n == r));
        if let Some((n, u, t)) = shown {
            let _ = write!(md, "Shows [{n} {t}]({u}/tree/{t}).\n\n");
        }
    }
    md.push_str(&credit_md().replace("](docs/screenshots/)", "](./)"));
    md
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The credit links each project's pinned release tree and the screenshots folder.
    #[test]
    fn the_credit_links_the_pinned_trees_and_the_screenshots_folder() {
        let c = credit_md();
        assert!(c.contains("[The screenshots](docs/screenshots/)"), "{c}");
        assert!(c.contains("[jq](https://github.com/jqlang/jq/tree/jq-1.8.2)"), "{c}");
        assert!(c.contains("[ripgrep](https://github.com/BurntSushi/ripgrep/tree/15.2.0)"), "{c}");
    }

    /// The gallery shows every shot with both schemes and the pinned tree it was taken from.
    #[test]
    fn the_gallery_lists_each_shot_with_its_pinned_tree() {
        let g = gallery_md();
        for (stem, alt, caption) in crate::site::SHOTS {
            assert!(g.contains(&format!("## {caption}")), "{caption}\n{g}");
            assert!(g.contains(alt), "{alt}");
            assert!(g.contains(&format!("{stem}-dark.webp")), "{stem}");
            assert!(g.contains(&format!("{stem}-light.webp")), "{stem}");
        }
        assert!(
            g.contains("Shows [ripgrep 15.2.0](https://github.com/BurntSushi/ripgrep/tree/15.2.0)"),
            "{g}"
        );
        assert!(
            g.contains("Shows [jq jq-1.8.2](https://github.com/jqlang/jq/tree/jq-1.8.2)"),
            "{g}"
        );
        assert_eq!(g.matches("Shows [").count(), crate::site::SHOTS.len(), "{g}");
    }
}
