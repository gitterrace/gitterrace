pub(super) const CHANGELOG: &str = "CHANGELOG.md";
/// The first line of a document written whole by `cargo xtask generate`.
const GENERATED: &str = "<!-- Generated by `cargo xtask generate`";

/// Where each published document is, so a relative link can be rewritten.
pub(super) struct Links<'a> {
    pages: BTreeMap<String, String>,
    repo: &'a str,
}

impl<'a> Links<'a> {
    pub(super) fn new(repo: &'a str) -> Self {
        let mut pages: BTreeMap<String, String> = on_site()
            .into_iter()
            .map(|(path, ..)| (path.to_owned(), page_path(stem(path))))
            .collect();
        pages.insert(CHANGELOG.to_owned(), "changelog/".to_owned());
        for (rel, _) in LEGAL {
            pages.insert(rel.to_owned(), legal_path(rel));
        }
        Self { pages, repo }
    }

    /// `dest`, written in the document at `from`, as a link that works on the site. An image the
    /// site does not carry is loaded from the repository, as raw bytes.
    pub(super) fn rewrite(&self, from: &str, dest: &str, image: bool) -> String {
        if dest.contains("://") || dest.starts_with("mailto:") || dest.starts_with('#') {
            return dest.to_owned();
        }
        let (file, anchor) = dest.split_once('#').unwrap_or((dest, ""));
        let dir = Path::new(from).parent().unwrap_or_else(|| Path::new(""));
        let target = normalize(&dir.join(file));
        let hash = if anchor.is_empty() { String::new() } else { format!("#{anchor}") };
        match self.pages.get(&target) {
            Some(page) => format!("/{page}{hash}"),
            None if image => format!("{}/raw/main/{target}", self.repo),
            None if file.ends_with('/') => format!("{}/tree/main/{target}{hash}", self.repo),
            None => format!("{}/blob/main/{target}{hash}", self.repo),
        }
    }
}

impl Links<'_> {
    /// Raw HTML (a `<picture>`) with each `src` and `srcset` pointed at where the file is.
    fn rewrite_html(&self, from: &str, html: &str) -> String {
        let mut out = html.to_owned();
        for attr in ["src", "srcset"] {
            let pat = format!(" {attr}=\"");
            let mut done = String::new();
            let mut rest = out.as_str();
            while let Some((before, after)) = rest.split_once(&pat) {
                let (value, tail) = after.split_once('"').unwrap_or((after, ""));
                done.push_str(before);
                let _ = write!(done, "{pat}{}\"", self.rewrite(from, value, true));
                rest = tail;
            }
            done.push_str(rest);
            out = done;
        }
        out
    }
}

pub(super) fn stem(path: &str) -> &str {
    let name = path.rsplit('/').next().unwrap_or(path);
    name.strip_suffix(".md").unwrap_or(name)
}

pub use crate::docs_index::slug;

/// Fails when two elements of one page share an id, so a link cannot mean two places.
pub fn check_unique_ids(path: &str, html: &str) -> Result<()> {
    let mut seen = std::collections::BTreeSet::new();
    for id in attrs(html, "id") {
        if !seen.insert(id) {
            anyhow::bail!("{path}: more than one heading has the id {id}");
        }
    }
    Ok(())
}

/// The site path of a legal page: `legal/<stem>/`, the same on every site.
pub fn legal_path(rel: &str) -> String {
    format!("legal/{}/", stem(rel))
}

/// The site path of a page, from its file stem.
pub fn page_path(stem: &str) -> String {
    format!("docs/{stem}/")
}

/// The heading slugs of one markdown text, in order.
#[cfg(test)]
pub fn anchors(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur: Option<String> = None;
    for ev in Parser::new_ext(text, gitterrace_web::markdown_options()) {
        match ev {
            Event::Start(Tag::Heading { .. }) => cur = Some(String::new()),
            Event::End(TagEnd::Heading(_)) => out.extend(cur.take().map(|h| slug(&h))),
            Event::Text(t) | Event::Code(t) => {
                if let Some(h) = cur.as_mut() {
                    h.push_str(&t);
                }
            }
            _ => {}
        }
    }
    out
}

/// The markdown of the document at `from` as HTML: each heading with the id `id` gives it (given
/// its level and text) and each relative link pointed at its page.
pub(super) fn body(
    text: &str,
    from: &str,
    links: &Links,
    id: &mut dyn FnMut(usize, &str) -> String,
) -> Result<String> {
    let mut events: Vec<Event> = Vec::new();
    let mut pending: Vec<Event> = Vec::new();
    let mut heading: Option<(HeadingLevel, String)> = None;
    for ev in Parser::new_ext(text, gitterrace_web::markdown_options()) {
        let ev = match ev {
            Event::Start(Tag::Link { link_type, dest_url, title, id }) => Event::Start(Tag::Link {
                link_type,
                dest_url: CowStr::from(links.rewrite(from, &dest_url, false)),
                title,
                id,
            }),
            Event::Start(Tag::Image { link_type, dest_url, title, id }) => {
                Event::Start(Tag::Image {
                    link_type,
                    dest_url: CowStr::from(links.rewrite(from, &dest_url, true)),
                    title,
                    id,
                })
            }
            Event::Html(h) => Event::Html(CowStr::from(links.rewrite_html(from, &h))),
            ev => ev,
        };
        match (&mut heading, ev) {
            (None, Event::Start(Tag::Heading { level, .. })) => {
                heading = Some((level, String::new()));
            }
            (Some((level, text)), Event::End(TagEnd::Heading(_))) => {
                events.push(Event::Start(Tag::Heading {
                    level: *level,
                    id: Some(CowStr::from(id(*level as usize, text))),
                    classes: vec![],
                    attrs: vec![],
                }));
                events.append(&mut pending);
                events.push(Event::End(TagEnd::Heading(*level)));
                heading = None;
            }
            (Some((_, text)), ev) => {
                if let Event::Text(t) | Event::Code(t) = &ev {
                    text.push_str(t);
                }
                pending.push(ev);
            }
            (None, ev) => events.push(ev),
        }
    }
    let mut out = String::new();
    html::push_html(&mut out, diagrams(events, from)?.into_iter());
    Ok(wrap_wide(&out))
}

/// `events` with each fenced `mermaid` block drawn as an inline SVG, numbered in page order so
/// two diagrams on one page keep their ids apart, and each other fence in a language the app
/// highlights coloured with its `s-*` classes. A block the site cannot draw is an error.
fn diagrams<'a>(events: Vec<Event<'a>>, from: &str) -> Result<Vec<Event<'a>>> {
    let mut out = Vec::with_capacity(events.len());
    let mut src: Option<(String, String)> = None;
    let mut n = 0;
    for ev in events {
        match (&mut src, ev) {
            (None, Event::Start(Tag::CodeBlock(CodeBlockKind::Fenced(lang))))
                if !lang.is_empty() && lang.as_ref() != "text" =>
            {
                src = Some((lang.to_string(), String::new()));
            }
            (Some((_, text)), Event::Text(t)) => text.push_str(&t),
            (Some((lang, text)), Event::End(TagEnd::CodeBlock)) if lang == "mermaid" => {
                n += 1;
                let svg = diagram::svg(text, &format!("diagram-{n}"), "How the crates depend")
                    .with_context(|| format!("{from}: diagram {n}"))?;
                out.push(Event::Html(CowStr::from(svg)));
                src = None;
            }
            (Some((lang, text)), Event::End(TagEnd::CodeBlock)) => {
                out.push(Event::Html(CowStr::from(code_block(text, lang))));
                src = None;
            }
            (Some(_), _) => {}
            (None, ev) => out.push(ev),
        }
    }
    Ok(out)
}

/// `code` as a `<pre>` block, highlighted when the app knows `lang` and escaped plain otherwise.
pub(super) fn code_block(code: &str, lang: &str) -> String {
    const MOST: usize = 64 * 1024;
    let lang = lang.split_whitespace().next().unwrap_or("");
    let body = gitterrace_web::highlight_block(code, lang, MOST).unwrap_or_else(|| esc(code));
    format!("<pre><code class=\"language-{}\">{body}</code></pre>\n", esc(lang))
}

/// `text` escaped for HTML text and attribute values.
fn esc(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            c => out.push(c),
        }
    }
    out
}

/// The site's lines at most `WIDTH` wide where a space allows: a line is broken at the last
/// space before the width, outside a tag and outside `<pre>`, where a newline reads as the space
/// it replaces. The pages are source files too, held to the repository's line width.
fn wrap_wide(html: &str) -> String {
    const WIDTH: usize = 100;
    let mut out = String::with_capacity(html.len());
    let mut pre = false;
    for line in html.split_inclusive('\n') {
        if line.contains("<pre") {
            pre = true;
        }
        if pre || line.trim_end().chars().count() <= WIDTH {
            out.push_str(line);
        } else {
            out.push_str(&break_line(line, WIDTH));
        }
        if line.contains("</pre>") {
            pre = false;
        }
    }
    out
}

/// The tags a table is built of: a newline before one is whitespace a table drops, so a table
/// row with no spaces can still break between its cells.
const TABLE_TAGS: [&str; 10] =
    ["<thead", "</thead", "<tbody", "</tbody", "<tr", "</tr", "<th", "</th", "<td", "</td"];

/// One line broken at spaces outside tags, or before a table tag, each piece at most `width`
/// wide where it can be.
fn break_line(line: &str, width: usize) -> String {
    let mut out = String::new();
    // `last` is where the line may break and how many bytes the break replaces: a space is
    // replaced by the newline, a table tag keeps its place after it.
    let (mut start, mut last, mut tag, mut col) = (0, None, false, 0);
    for (i, ch) in line.char_indices() {
        match ch {
            '<' => {
                let rest = &line[i..];
                let at_tag = TABLE_TAGS.iter().any(|t| {
                    rest.starts_with(t) && matches!(rest.as_bytes().get(t.len()), Some(b'>' | b' '))
                });
                if at_tag && i > start {
                    last = Some((i, 0));
                }
                tag = true;
            }
            '>' => tag = false,
            ' ' if !tag => last = Some((i, 1)),
            _ => {}
        }
        col += 1;
        if col > width
            && let Some((at, skip)) = last.take()
        {
            out.push_str(&line[start..at]);
            out.push('\n');
            start = at + skip;
            col = line[start..=i].chars().count();
        }
    }
    out.push_str(&line[start..]);
    out
}

/// The "On this page" rail of a document from its level 2 headings as (id, text): the app's
/// outline, so the site and the app list headings the same way. Empty below three headings.
pub(super) fn outline(h2s: &[(String, String)]) -> String {
    let items: Vec<(&str, &str)> = h2s.iter().map(|(i, t)| (i.as_str(), t.as_str())).collect();
    // The app writes the rail on one line; the site's pages are held to the line width and
    // length. Breaking between tags adds no whitespace, so the tags are packed into lines as
    // full as the width allows.
    let mut out = String::new();
    let mut line = 0;
    for piece in gitterrace_web::outline_rail(&items).split_inclusive(['>']) {
        let n = piece.chars().count();
        if line > 0 && line + n > 100 {
            out.push('\n');
            line = 0;
        }
        out.push_str(piece);
        line += n;
    }
    // The filter field's attributes go on two lines; whitespace between attributes is free.
    out.trim_end().replace("\" aria-label=\"Filter", "\"\naria-label=\"Filter")
}

/// The docs index page, `templates/docs_index.html`.
#[derive(Template)]
#[template(path = "docs_index.html")]
struct Index<'a> {
    lead: &'a str,
    groups: Vec<Group<'a>>,
}

/// One docs index group: (anchor slug, label) and its (link, title, what it covers) entries.
type Group<'a> = ((String, &'a str), Vec<(String, &'a str, String)>);

/// The docs index: every published document under the label of its group, as its title and
/// the line of what it covers.
fn index(docs: &[(String, String)], lead: &str) -> String {
    let mut groups: Vec<Group> = Vec::new();
    for (path, heading, what) in on_site() {
        let Some((_, title)) = docs.iter().find(|d| d.0 == path) else {
            continue;
        };
        if groups.last().is_none_or(|g| g.0.1 != heading) {
            groups.push(((slug(heading), heading), Vec::new()));
        }
        if let Some(g) = groups.last_mut() {
            g.1.push((page_path(stem(path)), title, what.replace('`', "")));
        }
    }
    let mut out = Index { lead, groups }.render().unwrap_or_default();
    out.push('\n');
    out
}

/// A document's title, its first `# ` line.
fn title_of(rel: &str, text: &str) -> Result<String> {
    text.lines()
        .find_map(|l| l.strip_prefix("# "))
        .map(str::to_owned)
        .with_context(|| format!("{rel} has no title"))
}

/// One page per published document, the docs index, the legal pages and the changelog.
/// Returns the files and every page path, for the sitemap and the link check.
pub(super) fn pages(root: &Path, site: &Site) -> Result<(Vec<Out>, Vec<String>)> {
    let links = Links::new(site.repo);
    let read = |rel: &str| {
        std::fs::read_to_string(root.join(rel)).with_context(|| format!("reading {rel}"))
    };
    let mut outs = Vec::new();
    let mut paths = vec!["docs/".to_owned()];
    let mut docs = Vec::new();
    for (rel, group, what) in on_site() {
        let text = read(rel)?;
        let title = title_of(rel, &text)?;
        let path = page_path(stem(rel));
        if docs.iter().any(|d: &(&str, String, String, &str, String, &str)| d.1 == path) {
            anyhow::bail!("{rel}: another document is already the page {path}");
        }
        docs.push((rel, path, title, what, text, group));
    }
    let order: Vec<(String, String, String)> =
        docs.iter().map(|(_, p, t, .., g)| (p.clone(), t.clone(), (*g).to_owned())).collect();
    let mut titles = Vec::new();
    for (rel, path, title, what, text, _) in docs {
        let mut h2s = Vec::new();
        let inner = body(&text, rel, &links, &mut |level, h| {
            let id = slug(h);
            if level == 2 {
                h2s.push((id.clone(), h.to_owned()));
            }
            id
        })?;
        let rail = outline(&h2s);
        let (heads, scripts) =
            if rail.is_empty() { (Vec::new(), Vec::new()) } else { (h2s, vec![outline_script()]) };
        let nav = docnav::nav(&order, &path, &heads);
        let html = page(
            site,
            &Body {
                title: &title,
                desc: &sentence(what),
                path: &path,
                inner: &inner,
                docnav: &nav.list,
                docs_menu: &nav.menu,
                menus: &nav.menus,
                pager: &nav.pager,
                rail: &rail,
                edit: Some((rel, text.starts_with(GENERATED))),
                scripts,
                ..Body::default()
            },
        );
        check_unique_ids(&path, &html)?;
        outs.push(Out::file(at(&format!("{path}index.html")), html));
        paths.push(path);
        titles.push((rel.to_owned(), title));
    }
    legal_pages(site, &links, &read, &mut outs, &mut paths)?;
    let lead = "Every document, by what you need. Each page is also a file in the repository.";
    outs.push(Out::file(
        at("docs/index.html"),
        page(
            site,
            &Body {
                title: "Documentation",
                desc: "How to install, use, run and look up gitterrace, by what you need.",
                path: "docs/",
                inner: &index(&titles, lead),
                ..Body::default()
            },
        ),
    ));
    let log = changelog::page(site, &links, &read(CHANGELOG)?)?;
    if let Out::File { body, .. } = &log {
        check_unique_ids(changelog::PATH, body)?;
    }
    outs.push(log);
    paths.push(changelog::PATH.to_owned());
    paths.sort();
    Ok((outs, paths))
}

/// The legal pages. A legal page's `<title>` and kicker are the word the footer links it by; its
/// h1 may be friendlier.
fn legal_pages(
    site: &Site,
    links: &Links,
    read: &dyn Fn(&str) -> Result<String>,
    outs: &mut Vec<Out>,
    paths: &mut Vec<String>,
) -> Result<()> {
    for (rel, label) in LEGAL {
        let text = read(rel)?;
        let path = legal_path(rel);
        let inner = body(&text, rel, links, &mut |_, h| slug(h))?;
        let what = crate::docs_index::covers(rel).unwrap_or_default();
        let html = page(
            site,
            &Body {
                title: label,
                desc: &sentence(what),
                path: &path,
                kicker: label,
                inner: &inner,
                ..Body::default()
            },
        );
        check_unique_ids(&path, &html)?;
        outs.push(Out::file(at(&format!("{path}index.html")), html));
        paths.push(path);
    }
    Ok(())
}

/// The index line of what a document covers, as a sentence for its meta description.
pub(super) fn sentence(what: &str) -> String {
    let what = what.replace('`', "");
    if what.ends_with('.') { what } else { format!("{what}.") }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Fences in a language the app highlights come out with its `s-*` spans and a language class;
    /// `text` and unknown fences stay plain and escaped.
    #[test]
    fn known_fences_are_highlighted_and_text_stays_plain() {
        let links = Links::new("https://r");
        let text = "```toml\n[x]\nname = \"a\"\n```\n\n\
                    ```bash\nif true; then echo \"a\"; fi\n```\n\n\
                    ```text\nname = \"a\" <b>\n```\n";
        let html = body(text, "docs/x.md", &links, &mut |_, h| slug(h)).expect("body");
        let blocks: Vec<&str> = html.split("<pre>").skip(1).collect();
        assert_eq!(blocks.len(), 3, "{html}");
        assert!(blocks[0].starts_with("<code class=\"language-toml\">"), "{html}");
        assert!(blocks[0].contains("class=\"s-"), "{html}");
        assert!(blocks[1].starts_with("<code class=\"language-bash\">"), "{html}");
        assert!(blocks[1].contains("class=\"s-"), "{html}");
        assert!(!blocks[2].contains("s-"), "{html}");
        assert!(blocks[2].contains("&lt;b&gt;"), "{html}");
        assert!(!html.contains("style="), "{html}");
    }
}
