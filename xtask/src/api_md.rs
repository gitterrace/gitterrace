//! `docs/api.md`, rendered from the live registries: [`ENDPOINTS`], [`insight_list`], the MCP tool
//! router and the cap constants. Never from scraped source.

use std::fmt::Write as _;

use gitterrace_api::{ENDPOINTS, ERROR_CODES, McpServer, Param, insight_list};

use crate::out::Out;

const PATH: &str = "docs/api.md";

const INTRO: &str = "\
Read-only. Everything is pinned to a revision (`rev`, default `HEAD`). Errors are
`{\"error\": {\"code\", \"message\"}}`, codes listed below. Every response carries an `ETag`
built from HEAD, every ref's target, the cache format, how far the cache is filled and the
configured counting defaults, so moving any branch or tag, the cache catching up or a changed
`insights` setting invalidates it. `If-None-Match` gets 304.
JSON is `snake_case`. The same endpoints as `OpenAPI` 3.1: [openapi.json](openapi.json).

The API of each repository lives at `/r/{name}/api/v1`.

Rust: `gitterrace_api::router(ApiState)` (nest under `/api/v1`), `gitterrace_api::serve_mcp(path, config)`.
";

#[expect(
    clippy::literal_string_with_formatting_args,
    reason = "`{name}` is the route placeholder the docs print, not a format argument"
)]
pub fn render() -> Out {
    let mut s = String::new();
    s.push_str("<!-- Generated by `cargo xtask generate`. Do not edit. -->\n\n# API\n\n");
    s.push_str(INTRO);
    s.push_str("\n| Status | `code` | Meaning |\n|---|---|---|\n");
    for (code, status, meaning) in ERROR_CODES {
        let _ = writeln!(s, "| {status} | `{code}` | {meaning} |");
    }
    s.push_str(
        "\nA 5xx `message` is always the same fixed text. The details go to the server log.\n",
    );
    let a = gitterrace_config::Api::default();
    let _ = writeln!(
        s,
        "\nAnswers are capped so one file cannot flood a client: `log` at {} per page, \
         `blob` at {} lines and {} KiB, `blame` at {} lines, each \
         with `truncated` when cut. The `[api]` section of `config.toml` sets each cap.",
        a.log_page_commits, a.blob_lines, a.blob_kb, a.blame_lines
    );

    s.push_str("\n## HTTP (`/api/v1`)\n\n| Endpoint | Query | Returns |\n| --- | --- | --- |\n");
    for e in ENDPOINTS {
        let query = e
            .params
            .iter()
            .map(|p| format!("`{}`", p.name))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(s, "| `GET {}` | {query} | {} |", e.path, e.returns);
    }
    s.push_str("\n### Parameters\n");
    for e in ENDPOINTS.iter().filter(|e| !e.params.is_empty()) {
        let _ = write!(s, "\n`{}`: {}\n\n", e.path, e.summary);
        s.push_str("| Name | Type | Required | Description |\n| --- | --- | --- | --- |\n");
        for Param {
            name,
            ty,
            required,
            description,
        } in e.params
        {
            let req = if *required { "yes" } else { "no" };
            let _ = writeln!(s, "| `{name}` | {ty} | {req} | {description} |");
        }
    }

    s.push_str(
        "\n## Insights\n\nServed at `GET /insights/{name}`. Every number is counted by one rule, see\n[How numbers are counted](internals/counting.md).\n\n| Name | Summary |\n| --- | --- |\n",
    );
    for (name, summary) in insight_list() {
        let _ = writeln!(s, "| `{name}` | {summary} |");
    }

    s.push_str(
        "\n## MCP (stdio)\n\n`git terrace mcp [path]` serves one repository.\n\n\
         | Tool | Read-only | Description | Parameters |\n| --- | --- | --- | --- |\n",
    );
    for t in McpServer::tool_docs() {
        let params = t
            .params
            .iter()
            .map(|p| {
                let opt = if p.required { "" } else { "?" };
                format!("`{}{opt}` ({})", p.name, p.ty)
            })
            .collect::<Vec<_>>()
            .join(", ");
        let ro = if t.read_only { "yes" } else { "no" };
        let desc = t.description.replace('\n', " ");
        let _ = writeln!(s, "| `{}` | {ro} | {desc} | {params} |", t.name);
    }
    s.push_str("\nA trailing `?` marks an optional parameter.\n");
    Out::file(PATH, s)
}
