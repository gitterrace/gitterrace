//! Generated blocks of `docs/actions.md`, `docs/architecture.md` and `docs/design.md`.

use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context as _, Result};
use gitterrace_actions::schema::{
    ACTION_KEYS, ENV_VARS, Item, KINDS, PAYLOAD_FIELDS, SCRIPT_KEYS, kind_name,
};

use crate::facts::Workspace;
use crate::out::Out;
use crate::readme_md::crate_diagram;
use crate::scripts::Script;

const ACTIONS: &str = "docs/actions.md";
const ARCH: &str = "docs/architecture.md";
const DESIGN: &str = "docs/design.md";

pub fn render(root: &Path, ws: &Workspace, scripts: &[Script]) -> Result<Vec<Out>> {
    Ok(vec![
        Out::block(ACTIONS, "kinds", kinds()),
        Out::block(ACTIONS, "payload", payload()),
        Out::block(ACTIONS, "env", env()),
        Out::block(ACTIONS, "action-keys", action_keys()),
        Out::block(ACTIONS, "scripts", script_table(scripts)),
        Out::block(ARCH, "crates", crate_diagram(ws)),
        Out::block(ARCH, "routes", routes()),
        Out::block(ARCH, "cache", cache()),
        Out::block(DESIGN, "tokens", tokens(root)?),
    ])
}

fn kinds() -> String {
    let rows: Vec<String> = KINDS
        .iter()
        .map(|(k, doc)| {
            format!(
                "`{}` ({})",
                kind_name(*k),
                doc.trim_end_matches('.').to_lowercase()
            )
        })
        .collect();
    format!("{}.\n", rows.join(", "))
}

fn payload() -> String {
    let mut s =
        String::from("| Field | Type | Always there | Description |\n| --- | --- | --- | --- |\n");
    for f in PAYLOAD_FIELDS {
        let _ = writeln!(
            s,
            "| `{}` | {} | {} | {} |",
            f.name,
            f.ty,
            yes(f.required),
            f.doc
        );
    }
    s
}

fn env() -> String {
    let names: Vec<String> = ENV_VARS.iter().map(|(k, _)| format!("`{k}`")).collect();
    format!("{}.\n", names.join(", "))
}

fn yes(b: bool) -> &'static str {
    if b { "yes" } else { "no" }
}

fn key_table(title: &str, intro: &str, items: &[Item]) -> String {
    let mut s = format!(
        "### {title}\n\n{intro}\n\n| Key | Type | Required | Default | Description |\n| --- | --- | --- | --- | --- |\n"
    );
    for i in items {
        let _ = writeln!(
            s,
            "| `{}` | {} | {} | {} | {} |",
            i.name,
            i.ty,
            yes(i.required),
            i.default,
            i.doc
        );
    }
    s
}

fn action_keys() -> String {
    [
        key_table(
            "`[[script]]`",
            "A command line written once, for several actions.",
            &SCRIPT_KEYS,
        ),
        key_table(
            "`[[action]]`",
            "One menu entry. It runs either its own `command` or a `script`.",
            &ACTION_KEYS,
        ),
    ]
    .join("\n")
}

fn script_table(scripts: &[Script]) -> String {
    let mut s = String::from("| Script | Does | Needs |\n| --- | --- | --- |\n");
    for sc in scripts {
        let _ = writeln!(
            s,
            "| [`{f}`](actions/{f}) | {} | {} |",
            sc.summary,
            sc.needs,
            f = sc.file
        );
    }
    s
}

fn routes() -> String {
    let mut s = String::from("| Route | Shows |\n| --- | --- |\n");
    for p in gitterrace_web::sitemap::PAGES {
        let _ = writeln!(s, "| {} | {} |", p.shown, p.does);
    }
    s
}

fn cache() -> String {
    let mut s = String::from("| File | Holds |\n| --- | --- |\n");
    for (name, doc) in gitterrace_index::CACHE_FILES {
        let _ = writeln!(s, "| `{name}` | {doc} |");
    }
    let _ = write!(
        s,
        "\nThe format version is `{}`.\n",
        gitterrace_index::FORMAT_VERSION
    );
    s
}

/// The role aliases below the generated markers of `tokens.css`, grouped by prefix.
fn tokens(root: &Path) -> Result<String> {
    let css = std::fs::read_to_string(root.join("crates/gitterrace-web/static/tokens.css"))
        .context("reading tokens.css")?;
    let roles = css
        .split("/* END generated by scripts/theme-gen.py */")
        .nth(1)
        .context("tokens.css has no END marker")?;
    let mut names: Vec<String> = Vec::new();
    for decl in roles.split(';') {
        let decl = decl.rsplit(['{', '\n']).next().unwrap_or("").trim();
        if let Some(rest) = decl.strip_prefix("--")
            && let Some((name, value)) = rest.split_once(':')
            && value.trim_start().starts_with("var(")
        {
            names.push(format!("`--{name}`"));
        }
    }
    Ok(format!(
        "The role aliases in `tokens.css`: {}.\n",
        names.join(", ")
    ))
}

#[cfg(test)]
mod tests {
    use super::tokens;

    #[test]
    fn role_alias_list_is_not_empty() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let text = tokens(&root).expect("tokens.css parses");
        assert!(text.contains("`--bg`"), "no role aliases found: {text}");
    }
}
