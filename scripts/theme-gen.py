#!/usr/bin/env python3
"""Generate gitterrace's theme files from the schwarzwald snapshot (stdlib only).

    scripts/theme-gen.py           write the files
    scripts/theme-gen.py --check   exit 1 if a role pair (PAIRS) is under its contrast minimum,
                                   or if a file differs from its generated form

shared/schwarzwald/check.py checks the snapshot itself: a sha256 and the exec bit per file
against manifest.json. Refresh the snapshot with schwarzwald's sync.py, never by editing it.
Reads shared/schwarzwald/tokens/{theme-tokens,design-tokens}.json. Writes
crates/gitterrace-web/static/tokens.css (between the markers only). Rust code reads
the vendored `schwarzwald` crate directly. Change the theme in schwarzwald, run its
sync.py, then this; never edit the generated parts by hand.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

# Parsed JSON token files: nested dicts whose shape lives in schwarzwald, not here.
Json = dict[str, Any]

ROOT = Path(__file__).resolve().parent.parent
SNAP = ROOT / "shared/schwarzwald"
CSS = ROOT / "crates/gitterrace-web/static/tokens.css"
BEGIN, END = (
    "/* BEGIN generated by scripts/theme-gen.py */",
    "/* END generated by scripts/theme-gen.py */",
)
THEME = "kandel"
SCRIM = "#0000004d"
# Floating layers only. Light and dark differ in strength, not in shape.
# Steps of the schwarzwald space grid that app.css uses; the rest stays out of the stylesheet.
SPACE_USED = {1, 2, 3, 4, 5, 6, 8, 16}
SHADOW = {"light": "0 8px 28px rgba(16,20,28,.12)", "dark": "0 8px 28px rgba(0,0,0,.5)"}
RING_ALPHA = {"light": "66", "dark": "80"}


def hexv(tok: Json, name: str) -> str:
    return str(tok[name]["hex"]).lower()


def mix(fg: str, bg: str, share: float) -> str:
    a = [int(fg[i : i + 2], 16) for i in (1, 3, 5)]
    b = [int(bg[i : i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(
        f"{round(x * share + y * (1 - share)):02x}" for x, y in zip(a, b)
    )


def luminance(c: str) -> float:
    def ch(i: int) -> float:
        x = int(c[i : i + 2], 16) / 255
        return x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4

    return 0.2126 * ch(1) + 0.7152 * ch(3) + 0.0722 * ch(5)


def contrast(a: str, b: str) -> float:
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


# (foreground, background, minimum) in resolved colours. Text needs 4.5:1 on every surface it
# is drawn on, built from the lists below so a new token joins the matrix by name. Control
# borders (--line-strong, drawn on inputs and buttons) need 3:1; the quiet divider --line only
# has to stay visible (1.15:1) because rules are not a control edge.
PAGE_SURFACES = ["n-1", "n-2", "n-3", "header", "raised"]
TEXT = ["n-6", "n-7", "n-9", "info", "accent", "add", "del", "warn"]
SYNTAX = [
    f"syn-{r}"
    for r in ("comment", "keyword", "string", "constant", "entity", "tag", "param")
]
ROW_SURFACES = ["add-bg", "del-bg", "warn-bg", "accent-soft"]
PAIRS: list[tuple[str, str, float]] = (
    [(t, s, 4.5) for t in TEXT for s in PAGE_SURFACES]
    + [(t, s, 4.5) for t in SYNTAX for s in ["n-1", "n-2", "raised"] + ROW_SURFACES]
    + [(t, s, 4.5) for t in ("n-9", "n-7", "accent") for s in ROW_SURFACES]
    + [("add", "add-hl", 4.5), ("del", "del-hl", 4.5), ("on-accent", "accent", 4.5)]
    + [("accent", s, 3) for s in ("n-1", "raised", "header")]
    + [("n-5", s, 3) for s in ("n-1", "n-2", "n-3", "header", "raised")]
    + [("n-4", s, 1.15) for s in ("n-1", "n-2", "header", "raised")]
)


def contrast_problems(tokens: Json) -> list[str]:
    bad: list[str] = []
    for mode in ("light", "dark"):
        col = colours(tokens, mode)
        for fg, bg, need in PAIRS:
            got = contrast(col[fg], col[bg])
            if got < need:
                bad.append(f"{mode}: --{fg} on --{bg} is {got:.2f}:1, needs {need}:1")
    return bad


def colours(tokens: Json, mode: str) -> dict[str, str]:
    t: Json = tokens["themes"][THEME][mode]

    def h(n: str) -> str:
        return hexv(t, n)

    # Order is the order in the stylesheet. Names are the roles app.css uses.
    out = {
        "n-0": h("surfaces.window"),
        "n-1": h("surfaces.bg"),
        "n-2": h("surfaces.soft"),
        "n-3": h("surfaces.hover"),
        "n-4": h("surfaces.line"),
        "n-5": h("surfaces.line-strong"),
        "n-6": h("ink.tertiary"),
        "n-7": h("ink.secondary"),
        "n-9": h("ink.primary"),
        "header": h("surfaces.header"),
        "raised": h("surfaces.raised"),
        "scrim": SCRIM,
        "accent": h("accent-ink"),
        "accent-fg": h("accent-ink"),
        "accent-soft": mix(
            h("accent-ink"), h("surfaces.bg"), tokens["shares"]["selected-row"]
        ),
        "ring": h("accent-ink") + RING_ALPHA[mode],
        # Text on an accent fill: whichever of white and the page ink reads better.
        "on-accent": max(
            ("#ffffff", h("surfaces.bg")), key=lambda c: contrast(c, h("accent-ink"))
        ),
        "add": h("positive"),
        "add-bg": h("code.add-row"),
        "add-hl": h("code.add-word"),
        "del": h("danger"),
        "del-bg": h("code.del-row"),
        "del-hl": h("code.del-word"),
        "warn": h("caution"),
        "warn-bg": h("code.warn-row"),
        "info": h("info"),
        "done": h("positive"),
    }
    for i in range(5):
        out[f"seq-{i}"] = h(f"heat.{i}")
    for i in range(1, 9):
        out[f"cat-{i}"] = h(f"series.{i}")
    for r in ("comment", "keyword", "string", "constant", "entity", "tag", "param"):
        out[f"syn-{r}"] = h(f"code.syntax.{r}")
    return out


def block(selector: str, mode: str, col: dict[str, str], indent: str = "") -> str:
    items = [f"--{k}:{v};" for k, v in col.items()] + [f"--shadow-2:{SHADOW[mode]};"]
    rows = [" ".join(items[i : i + 8]) for i in range(0, len(items), 8)]
    body = "\n".join(indent + r for r in rows)
    return f"{selector}{{color-scheme:{mode};\n{body}\n}}"


def fonts(design: Json) -> list[str]:
    f: Json = design["font"]
    faces = [
        ("Fraunces", "fraunces", "100 900"),
        ("Bricolage Grotesque", "bricolage-grotesque", "200 800"),
        ("JetBrains Mono", "jetbrains-mono", "100 800"),
    ]
    assert (
        f["title"]["web"] == "Fraunces"
        and f["body"]["web"].startswith("Bricolage")
        and f["mono"]["web"] == "JetBrains Mono"
    )
    lines = [
        f'@font-face{{font-family:"{fam}";src:url(/static/fonts/{slug}.woff2) format("woff2");'
        f"font-weight:{w};font-display:swap}}"
        for fam, slug, w in faces
    ]

    def stack(k: str) -> str:
        return ",".join(
            f'"{x}"' if " " in x else x for x in [f[k]["web"]] + f[k]["fallback"]
        )

    lines.append(
        f':root{{--font-title:{stack("title")};--font-body:{stack("body")};--font-mono:{stack("mono")},"SF Mono",Consolas,monospace;}}'
    )
    return lines


def scales(design: Json) -> str:
    d = design
    names = {11: "2xs", 12: "xs", 13: "sm", 15: "base", 16: "md", 20: "lg", 26: "xl"}
    t = "".join(f"--text-{names[p]}:{p}px;" for p in d["type"]["scalePx"])
    s = "".join(
        f"--space-{i + 1}:{p}px;"
        for i, p in enumerate(d["space"]["stepsPx"])
        if i + 1 in SPACE_USED
    )
    m = d["motion"]
    mo = f"--ease:{m['easing'].replace(', ', ',')};" + "".join(
        f"--{n}:{m['durationMs'][k]}ms;"
        for n, k in (("dur-fast", "hover"), ("dur-slow", "progress"))
    )
    return f":root{{{t}\n{s}\n--radius:{d['radius']['webPx']}px;\n{mo}}}"


def gen_css(tokens: Json, design: Json, old: str) -> str:
    light, dark = colours(tokens, "light"), colours(tokens, "dark")
    parts = fonts(design) + [
        scales(design),
        block(":root", "light", light),
        "@media (prefers-color-scheme:dark){"
        + block(":root:not([data-theme=light])", "dark", dark)
        + "}",
        block(":root[data-theme=dark]", "dark", dark),
    ]
    b, e = old.index(BEGIN), old.index(END)
    return old[:b] + BEGIN + "\n" + "\n".join(parts) + "\n" + old[e:]


def main() -> int:
    tokens = json.loads((SNAP / "tokens/theme-tokens.json").read_text())
    design = json.loads((SNAP / "tokens/design-tokens.json").read_text())
    want = {CSS: gen_css(tokens, design, CSS.read_text())}
    if "--check" in sys.argv:
        low = contrast_problems(tokens)
        for line in low:
            print(line)
        if low:
            return 1
        bad = [str(p.relative_to(ROOT)) for p, s in want.items() if p.read_text() != s]
        for b in bad:
            print(f"differs from generated: {b}; run scripts/theme-gen.py")
        return 1 if bad else 0
    for p, s in want.items():
        p.write_text(s)
    return 0


if __name__ == "__main__":
    sys.exit(main())
