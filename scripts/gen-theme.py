#!/usr/bin/env python3
"""Generate gitterrace's theme files from the schwarzwald snapshot (stdlib only).

    scripts/gen-theme.py           write the files
    scripts/gen-theme.py --check   exit 1 naming a file that differs from its generated form

Reads theme/schwarzwald/{theme-tokens,design-tokens}.json. Writes
crates/gitterrace-web/static/tokens.css (between the markers only). Rust code reads
the vendored `schwarzwald` crate directly. Change the theme in schwarzwald, run its
sync.py, then this; never edit the generated parts by hand.
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAP = ROOT / "theme/schwarzwald"
CSS = ROOT / "crates/gitterrace-web/static/tokens.css"
BEGIN, END = "/* BEGIN generated by scripts/gen-theme.py */", "/* END generated by scripts/gen-theme.py */"
THEME = "kandel"
SCRIM = "#0000004d"
# Floating layers only. Light and dark differ in strength, not in shape.
SHADOW = {"light": "0 8px 28px rgba(16,20,28,.12)", "dark": "0 8px 28px rgba(0,0,0,.5)"}
RING_ALPHA = {"light": "66", "dark": "80"}


def hexv(tok, name):
    return tok[name]["hex"].lower()


def mix(fg, bg, share):
    a = [int(fg[i:i + 2], 16) for i in (1, 3, 5)]
    b = [int(bg[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x * share + y * (1 - share)):02x}" for x, y in zip(a, b))


def colours(tokens, mode):
    t = tokens["themes"][THEME][mode]
    h = lambda n: hexv(t, n)
    # Order is the order in the stylesheet. Names are the roles app.css uses.
    out = {
        "n-0": h("surfaces.window"), "n-1": h("surfaces.bg"), "n-2": h("surfaces.soft"),
        "n-3": h("surfaces.hover"), "n-4": h("surfaces.line"), "n-5": h("surfaces.line-strong"),
        "n-6": h("ink.tertiary"), "n-7": h("ink.secondary"), "n-9": h("ink.primary"),
        "header": h("surfaces.header"), "raised": h("surfaces.raised"), "scrim": SCRIM,
        "accent": h("accent-ink"), "accent-fg": h("accent-ink"), "accent-fill": h("accent"),
        "accent-soft": mix(h("accent-ink"), h("surfaces.bg"), tokens["shares"]["selected-row"]),
        "selection": h("code.selection"), "focus": h("accent-ink"),
        "ring": h("accent-ink") + RING_ALPHA[mode], "on-accent": "#ffffff",
        "add": h("positive"), "add-bg": h("code.add-row"), "add-hl": h("code.add-word"),
        "del": h("danger"), "del-bg": h("code.del-row"), "del-hl": h("code.del-word"),
        "warn": h("caution"), "warn-bg": h("code.warn-row"), "info": h("info"), "done": h("positive"),
    }
    for i in range(5):
        out[f"seq-{i}"] = h(f"heat.{i}")
    for i in range(1, 9):
        out[f"cat-{i}"] = h(f"series.{i}")
    for r in ("comment", "keyword", "string", "constant", "entity", "tag", "param"):
        out[f"syn-{r}"] = h(f"code.syntax.{r}")
    return out


def block(selector, mode, col, indent=""):
    items = [f"--{k}:{v};" for k, v in col.items()] + [f"--shadow-2:{SHADOW[mode]};"]
    rows = [" ".join(items[i:i + 8]) for i in range(0, len(items), 8)]
    body = "\n".join(indent + r for r in rows)
    return f"{selector}{{color-scheme:{mode};\n{body}\n}}"


def fonts(design):
    f = design["font"]
    faces = [("Fraunces", "fraunces", "100 900"), ("Bricolage Grotesque", "bricolage-grotesque", "200 800"),
             ("JetBrains Mono", "jetbrains-mono", "100 800")]
    assert f["title"]["web"] == "Fraunces" and f["body"]["web"].startswith("Bricolage") and f["mono"]["web"] == "JetBrains Mono"
    lines = [f'@font-face{{font-family:"{fam}";src:url(/static/fonts/{slug}.woff2) format("woff2");'
             f'font-weight:{w};font-display:swap}}' for fam, slug, w in faces]
    stack = lambda k: ",".join(f'"{x}"' if " " in x else x for x in [f[k]["web"]] + f[k]["fallback"])
    lines.append(f":root{{--font-title:{stack('title')};--font-body:{stack('body')};--font-mono:{stack('mono')},\"SF Mono\",Consolas,monospace;}}")
    return lines


def scales(design):
    d = design
    names = {11: "2xs", 12: "xs", 13: "sm", 15: "base", 16: "md", 20: "lg", 26: "xl"}
    t = "".join(f"--text-{names[p]}:{p}px;" for p in d["type"]["scalePx"])
    s = "".join(f"--space-{i + 1}:{p}px;" for i, p in enumerate(d["space"]["stepsPx"]))
    m = d["motion"]
    mo = f"--ease:{m['easing'].replace(', ', ',')};" + "".join(
        f"--{n}:{m['durationMs'][k]}ms;" for n, k in (("dur-fast", "hover"), ("dur", "popover"), ("dur-slow", "progress")))
    return f":root{{{t}\n{s}\n--radius:{d['radius']['webPx']}px;\n{mo}}}"


def gen_css(tokens, design, old):
    light, dark = colours(tokens, "light"), colours(tokens, "dark")
    parts = fonts(design) + [
        scales(design),
        block(":root", "light", light),
        "@media (prefers-color-scheme:dark){" + block(":root:not([data-theme=light])", "dark", dark) + "}",
        block(":root[data-theme=dark]", "dark", dark),
    ]
    b, e = old.index(BEGIN), old.index(END)
    return old[:b] + BEGIN + "\n" + "\n".join(parts) + "\n" + old[e:]


def main():
    tokens = json.loads((SNAP / "theme-tokens.json").read_text())
    design = json.loads((SNAP / "design-tokens.json").read_text())
    want = {CSS: gen_css(tokens, design, CSS.read_text())}
    if "--check" in sys.argv:
        bad = [str(p.relative_to(ROOT)) for p, s in want.items() if p.read_text() != s]
        for b in bad:
            print(f"differs from generated: {b}; run scripts/gen-theme.py")
        return 1 if bad else 0
    for p, s in want.items():
        p.write_text(s)
    return 0


sys.exit(main())
